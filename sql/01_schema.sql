--Builds the base 3 tables :
-- qa_rules : dictionary of rules - new rule will be just new line in 
-- qa_runs - log of runs: when control was run, which layer and result
-- qa_results - results: wchich object break the whenewer rules, wich run it was
DROP TABLE IF EXISTS qa_results;
DROP TABLE IF EXISTS qa_runs;
DROP TABLE IF EXISTS qa_rules;

CREATE TABLE qa_rules(
	rule_id   	integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY;
	rule_name 	varchar(50) UNIQUE NOT NULL,
	description varchar(200),
	severity 	varchar(10) NOT NULL CHECK (severity IN ('error','warning')),
	target_layer varchar(50)
);

CREATE TABLE qa_runs (
	run_id		integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	layer_name  varchar(50)  NOT NULL,
	started_at  timestamp NOT NULL DEFAULT now(),
	finished_at timestamp,
	status		varchar(10) NOT NULL DEFAULT 'running'
				CHECK (status IN ('running', 'success', 'failed')),
	triggered_by varchar(20) NOT NULL
				CHECK (triggered_by IN ('manual', 'scheduled'))
	
);

CREATE TABLE qa_results(
	result_id	integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	run_id		integer NOT NULL REFERENCES qa_runs(run_id) ON DELETE 
	rule_id		integer NOT NULL REFERENCES qa_rules(rule_id) ON DELETE RESTRICT,
	feature_id  varchar(50) NOT NULL,
	detail		varchar(200),
	created_at  timestamp NOT NULL DEFAULT now()
)
